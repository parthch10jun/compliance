// Helper functions
export const getMatrixById = (id: string): AuthorityMatrix | undefined => {
  return mockAuthorityMatrices.find(matrix => matrix.id === id);
};

export const getMatrixByFunction = (func: string): AuthorityMatrix | undefined => {
  return mockAuthorityMatrices.find(matrix => matrix.function === func);
};

export const getActiveMatrices = (): AuthorityMatrix[] => {
  return mockAuthorityMatrices.filter(matrix => matrix.status === 'Active');
};

export const getTotalAuthorityEntries = (): number => {
  return mockAuthorityMatrices.reduce((total, matrix) => total + matrix.entries.length, 0);
};
